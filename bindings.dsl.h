/* hsc2hs --cross-compile defines HSC2HS_ASM and replaces hsc_printf,
 * hsc_putchar, hsc_fputs, and hsc_mangle with assembly-record emitters.
 * Identifier macros pass a char* expression through to hsc_mangle. That
 * expression has to be a string literal (or a local -O2 folds back to
 * one). A strcpy into char fname[500][1000] is not an "i" immediate, and
 * clang 21 will not unroll that loop. */
#  undef printf
#  undef putchar
#  undef fputs
#  define printf(...)  hsc_printf(__VA_ARGS__)
#  define putchar(c)   hsc_putchar(c)
#  define fputs(s, fp) hsc_fputs(s, fp)
#  if defined(__clang__)
#    define BC_UNROLL_LOOP _Pragma("clang loop unroll(full)")
#  elif defined(__GNUC__) && __GNUC__ >= 8
#    define BC_UNROLL_LOOP _Pragma("GCC unroll 256")
#  else
#    define BC_UNROLL_LOOP
#  endif
#else
#  define BC_UNROLL_LOOP
#endif

